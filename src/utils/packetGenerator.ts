export function computeFingerprintId(mac: string): string {
  const clean = mac.replace(/[^a-fA-F0-9]/g, '').toUpperCase();
  let hash = 0x811c9dc5;
  for (let i = 0; i < clean.length; i++) {
    hash ^= clean.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  const checksum = (Math.abs(hash) % 0xffff).toString(16).padStart(4, '0').toUpperCase();
  return `FP-${clean.slice(0, 4)}-${clean.slice(8, 12)}-${checksum}`;
}

export function generateRawHex(type: string, mac: string, ssid?: string): string {
  const cleanMac = mac.replace(/:/g, '');
  const prefix = type.includes('BLE') ? '0201061aff4c000215' : '40000000ffffffffffff';
  const ssidHex = ssid ? Array.from(ssid).map(c => c.charCodeAt(0).toString(16).padStart(2, '0')).join('') : '4c41422d54455354';
  const padding = '008000003014010882848b960c12182432043048606c';
  const combined = `${prefix}${cleanMac}${ssidHex}${padding}`.toUpperCase();
  // Format into bytes
  const bytes: string[] = [];
  for (let i = 0; i < combined.length; i += 2) {
    bytes.push(combined.substr(i, 2));
  }
  while (bytes.length < 48) {
    bytes.push(Math.floor(Math.random() * 256).toString(16).padStart(2, '0').toUpperCase());
  }
  return bytes.slice(0, 48).join(' ');
}

